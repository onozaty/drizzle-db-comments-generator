import { describe, expect, it } from "vitest";
import { diff, toMigrationSql } from "./diff";
import type { CommentsState } from "./state";

describe("diff", () => {
  it("outputs all comments when there is no previous state", () => {
    // Arrange
    const next: CommentsState = { '"users"': { table: "Users", columns: { id: "User ID", name: "Name" } } };

    // Act
    const blocks = diff({}, next);

    // Assert
    expect(blocks).toEqual([
      [
        '-- "users"',
        `COMMENT ON TABLE "users" IS 'Users';`,
        "--> statement-breakpoint",
        `COMMENT ON COLUMN "users"."id" IS 'User ID';`,
        "--> statement-breakpoint",
        `COMMENT ON COLUMN "users"."name" IS 'Name';`,
      ].join("\n"),
    ]);
  });

  it("outputs only changed and added comments", () => {
    // Arrange
    const prev: CommentsState = { '"users"': { table: "Users", columns: { id: "User ID", name: "Name" } } };
    const next: CommentsState = {
      '"users"': { table: "Users", columns: { id: "User ID", name: "Full name", email: "Email" } },
    };

    // Act
    const blocks = diff(prev, next);

    // Assert
    expect(blocks).toEqual([
      [
        '-- "users"',
        `COMMENT ON COLUMN "users"."name" IS 'Full name';`,
        "--> statement-breakpoint",
        `COMMENT ON COLUMN "users"."email" IS 'Email';`,
      ].join("\n"),
    ]);
  });

  it("sets removed comments to NULL", () => {
    // Arrange
    const prev: CommentsState = { '"users"': { table: "Users", columns: { id: "User ID", name: "Name" } } };
    const next: CommentsState = { '"users"': { columns: { id: "User ID" } } };

    // Act
    const blocks = diff(prev, next);

    // Assert
    expect(blocks).toEqual([
      [
        '-- "users"',
        `COMMENT ON TABLE "users" IS NULL;`,
        "--> statement-breakpoint",
        `COMMENT ON COLUMN "users"."name" IS NULL;`,
      ].join("\n"),
    ]);
  });

  it("returns an empty array when nothing changed", () => {
    // Arrange
    const state: CommentsState = { '"users"': { table: "Users", columns: { id: "User ID" } } };

    // Act
    const blocks = diff(state, structuredClone(state));

    // Assert
    expect(blocks).toEqual([]);
  });

  it("ignores tables that disappeared since the previous state", () => {
    // Arrange
    const prev: CommentsState = { '"users"': { table: "Users", columns: {} } };

    // Act
    const blocks = diff(prev, {});

    // Assert
    expect(blocks).toEqual([]);
  });

  it.each([
    { name: "escapes single quotes", comment: "It's", expected: `'It''s'` },
    { name: "keeps line breaks", comment: "Line 1\nLine 2", expected: `'Line 1\nLine 2'` },
  ])("$name", ({ comment, expected }) => {
    // Arrange
    const next: CommentsState = { '"users"': { table: comment, columns: {} } };

    // Act
    const blocks = diff({}, next);

    // Assert
    expect(blocks).toEqual([`-- "users"\nCOMMENT ON TABLE "users" IS ${expected};`]);
  });

  it("outputs a block per table", () => {
    // Arrange
    const next: CommentsState = {
      '"users"': { table: "Users", columns: {} },
      '"auth"."sessions"': { table: "Sessions", columns: {} },
    };

    // Act
    const blocks = diff({}, next);

    // Assert
    expect(blocks).toEqual([
      `-- "users"\nCOMMENT ON TABLE "users" IS 'Users';`,
      `-- "auth"."sessions"\nCOMMENT ON TABLE "auth"."sessions" IS 'Sessions';`,
    ]);
  });
});

describe("toMigrationSql", () => {
  it("joins blocks with statement breakpoints after a header", () => {
    // Arrange
    const blocks = ["-- a\nSQL A;", "-- b\nSQL B;"];

    // Act
    const sql = toMigrationSql(blocks);

    // Assert
    expect(sql).toBe(
      [
        "-- Generated by generate-db-comments",
        "",
        "-- a",
        "SQL A;",
        "--> statement-breakpoint",
        "",
        "-- b",
        "SQL B;",
        "",
      ].join("\n"),
    );
  });
});
