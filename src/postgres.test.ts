import { describe, expect, it } from "vitest";
import type { CommentChange } from "./diff";
import { toPostgresSql } from "./postgres";

const HEADER = "-- Generated by drizzle-db-comments-generator\n\n";

describe("toPostgresSql", () => {
  it("generates table and column comments with a block per table", () => {
    // Arrange
    const changes: CommentChange[] = [
      { target: "table", table: "users", comment: "Users" },
      { target: "column", table: "users", column: "id", comment: "User ID" },
      { target: "column", table: "posts", column: "title", comment: "Title" },
    ];

    // Act
    const sql = toPostgresSql(changes);

    // Assert
    expect(sql).toBe(
      [
        "-- Generated by drizzle-db-comments-generator",
        "",
        '-- "users"',
        `COMMENT ON TABLE "users" IS 'Users';`,
        "--> statement-breakpoint",
        `COMMENT ON COLUMN "users"."id" IS 'User ID';`,
        "--> statement-breakpoint",
        "",
        '-- "posts"',
        `COMMENT ON COLUMN "posts"."title" IS 'Title';`,
        "",
      ].join("\n"),
    );
  });

  it("removes comments with NULL", () => {
    // Arrange
    const changes: CommentChange[] = [{ target: "column", table: "users", column: "id", comment: null }];

    // Act
    const sql = toPostgresSql(changes);

    // Assert
    expect(sql).toBe(`${HEADER}-- "users"\nCOMMENT ON COLUMN "users"."id" IS NULL;\n`);
  });

  it("qualifies tables in a schema with the schema", () => {
    // Arrange
    const changes: CommentChange[] = [
      { target: "column", schema: "auth", table: "users", column: "id", comment: "User ID" },
    ];

    // Act
    const sql = toPostgresSql(changes);

    // Assert
    expect(sql).toBe(`${HEADER}-- "auth"."users"\nCOMMENT ON COLUMN "auth"."users"."id" IS 'User ID';\n`);
  });

  it.each([
    { name: "escapes single quotes in comments", comment: "It's", expected: `'It''s'` },
    { name: "keeps line breaks in comments", comment: "Line 1\nLine 2", expected: `'Line 1\nLine 2'` },
  ])("$name", ({ comment, expected }) => {
    // Arrange
    const changes: CommentChange[] = [{ target: "table", table: "users", comment }];

    // Act
    const sql = toPostgresSql(changes);

    // Assert
    expect(sql).toBe(`${HEADER}-- "users"\nCOMMENT ON TABLE "users" IS ${expected};\n`);
  });

  it("escapes double quotes in identifiers", () => {
    // Arrange
    const changes: CommentChange[] = [
      { target: "column", schema: 'my"schema', table: 'my"table', column: 'my"column', comment: "Comment" },
    ];

    // Act
    const sql = toPostgresSql(changes);

    // Assert
    expect(sql).toContain(`COMMENT ON COLUMN "my""schema"."my""table"."my""column" IS 'Comment';`);
  });

  it.each([
    { name: "without a schema", schema: undefined, expected: `-- "status"\nCOMMENT ON TYPE "status" IS 'Status';` },
    {
      name: "with a schema",
      schema: "shop",
      expected: `-- "shop"."status"\nCOMMENT ON TYPE "shop"."status" IS 'Status';`,
    },
  ])("generates enum comments $name", ({ schema, expected }) => {
    // Arrange
    const changes: CommentChange[] = [{ target: "enum", schema, name: "status", comment: "Status" }];

    // Act
    const sql = toPostgresSql(changes);

    // Assert
    expect(sql).toBe(`${HEADER}${expected}\n`);
  });

  it("does not mix up an enum and a table with the same name", () => {
    // Arrange
    const changes: CommentChange[] = [
      { target: "enum", name: "status", comment: "Enum" },
      { target: "table", table: "status", comment: "Table" },
    ];

    // Act
    const sql = toPostgresSql(changes);

    // Assert
    expect(sql).toBe(
      `${HEADER}-- "status"\nCOMMENT ON TYPE "status" IS 'Enum';\n--> statement-breakpoint\n\n-- "status"\nCOMMENT ON TABLE "status" IS 'Table';\n`,
    );
  });
});
