import type { CommentsState, TableComments } from "./state";

const BREAKPOINT = "\n--> statement-breakpoint\n";

const literal = (s: string | undefined) => (s === undefined ? "NULL" : `'${s.replace(/'/g, "''")}'`);

/**
 * Generates `COMMENT ON` statements for the comments that changed between the two states.
 * Returns one block per table, or an empty array if nothing changed.
 */
export function diff(prev: CommentsState, next: CommentsState): string[] {
  const blocks: string[] = [];
  for (const [table, n] of Object.entries(next)) {
    const p: TableComments = prev[table] ?? { columns: {} };
    const lines: string[] = [];
    if (p.table !== n.table) lines.push(`COMMENT ON TABLE ${table} IS ${literal(n.table)};`);
    const columns = new Set([...Object.keys(p.columns), ...Object.keys(n.columns)]);
    for (const column of columns) {
      if (p.columns[column] !== n.columns[column]) {
        lines.push(`COMMENT ON COLUMN ${table}."${column}" IS ${literal(n.columns[column])};`);
      }
    }
    if (lines.length > 0) blocks.push(`-- ${table}\n${lines.join(BREAKPOINT)}`);
  }
  // Tables that disappeared since the previous state are left untouched, since the tables themselves are likely dropped
  return blocks;
}

/** Builds the content of the migration file from the blocks returned by `diff`. */
export function toMigrationSql(blocks: string[]): string {
  return `-- Generated by generate-db-comments\n\n${blocks.join(`${BREAKPOINT}\n`)}\n`;
}
